-- 3. Inner Join for Order Details
-- Join orders, order_items, and products to display detailed line items.
select * from capstone.orders as o
inner join capstone.order_items as oi
on o.order_id = oi.order_id
inner join capstone.products as p
on oi.product_id = p.product_id;

-- 4. Total Sales by Store
-- Write a query to group sales (total_price) by each store_id.
select sum(oi.Total_price) as Total_Sale ,s.store_id from capstone.order_items as oi
join capstone.orders as o
on o.order_id = oi.order_id
join capstone.stores as s
on o.store_id = s.store_id
group by s.store_id;

-- 5. Top 5 Selling Products
-- Use ORDER BY and LIMIT to get the top 5 most sold products by quantity
select sum(oi.quantity) as Quantity , p.product_name from capstone.order_items as oi
inner join capstone.products as p 
on oi.product_id = p.product_id
group by p.product_name
order by Quantity desc limit 5;

-- 6. Customer Purchase Summary
-- For each customer, return total orders placed, total items purchased,
-- and total revenue.
select o.customer_id , count(oi.order_id) as TotalOrder, sum(oi.Total_price) as TotalRevenue, sum(oi.Quantity) as Totalitem_Purchase from capstone.orders as o
inner join capstone.order_items as oi
on o.order_id = oi.order_id
group by o.customer_id
order by TotalOrder,TotalRevenue,Totalitem_Purchase;

-- 7. Segment Customers by Total Spend
-- Write a query to classify customers into spending brackets (e.g., low,
-- medium, high).
select o.customer_id,sum(oi.Total_price) as Total_spending ,
case
when sum(Total_price) <10000 then "Low"
when sum(Total_price) between 10000 and 15000 then "Medium"
else "High"
end as segments
from capstone.orders as o
inner join capstone.order_items as oi
on o.order_id = oi.order_id
group by o.customer_id;

-- 8. Staff Performance Analysis
-- Analyze total revenue generated by each staff member based on their
-- handled orders.
select s.staff_id,sum(oi.Total_price) as Total_Revenue from
capstone.orders as o
join capstone.staffs as s
on s.staff_id = o.staff_id
join capstone.order_items as oi
on o.order_id = oi.order_id
group by s.staff_id;

-- 9. Stock Alert Query
-- Write a query to list products where stock quantity < 10 in any store.
select st.store_id,p.product_id,p.product_name,s.quantity from
capstone.stocks as s
join capstone.stores as st
on s.store_id =st.store_id
join capstone.products as p
on p.product_id = s.product_id
where s.quantity<10;

